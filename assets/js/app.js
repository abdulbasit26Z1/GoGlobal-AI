(() => {
  const $ = (selector) => document.querySelector(selector);
  const state = {
    catalogue: {},
    trip: null,
    sessions: JSON.parse(localStorage.getItem('gg_sessions') || '[]'),
    sessionId: crypto.randomUUID ? crypto.randomUUID() : String(Date.now())
  };

  const money = (value) => `PKR ${Number(value || 0).toLocaleString('en-PK')}`;
  const escapeHtml = (value) => String(value ?? '').replace(/[&<>"']/g, (char) => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#039;'
  }[char]));
  const sessionTitle = (value) => value.replace(/^(show me|build me|i want|plan|search|explore|find|book)\s+/i, '').slice(0, 26);

  const getApiEndpoint = () => {
    const path = window.location.pathname;
    if (path.endsWith('/api/') || path.endsWith('/api/index.php')) {
      return 'api.php';
    }
    return '/api/api.php';
  };

  async function request(payload) {
    const endpoint = getApiEndpoint();
    const response = await fetch(endpoint, {
      method: 'POST',
      headers: {'Content-Type': 'application/json'},
      body: JSON.stringify(payload)
    });
    const text = await response.text();
    let data;
    try {
      data = JSON.parse(text);
    } catch (e) {
      throw new Error('API returned invalid JSON response. Please check server configuration.');
    }
    if (!response.ok || !data.ok) throw new Error(data.error || 'The concierge could not respond.');
    return data;
  }

  async function loadCatalogue() {
    const endpoint = getApiEndpoint();
    const response = await fetch(endpoint);
    const text = await response.text();
    let data = {};
    try {
      data = JSON.parse(text);
    } catch (e) {
      console.error('Failed to parse catalogue response:', text);
      showToast('Catalogue could not be loaded.');
      return;
    }
    state.catalogue = data.catalogue || {};
    const totalCount = Object.values(state.catalogue).reduce((total, list) => total + (list ? list.length : 0), 0);
    $('#catalogCount').textContent = `${totalCount}+ items`;
    renderCatalog('all');
  }

  function appendMessage(text, role = 'ai', content = '', source = 'ai') {
    const node = document.createElement('div');
    node.className = `message ${role}`;

    if (role === 'user') {
      node.innerHTML = `<div class="bubble">${escapeHtml(text)}</div>`;
    } else {
      const isAi = source === 'ai';
      const avatarLabel = isAi ? '✦ AI' : '💻 PC';
      const avatarClass = isAi ? 'avatar ai' : 'avatar computer';
      const sourceBadge = isAi
        ? '<div class="source-badge ai"><span class="badge-dot">●</span> Gemini AI</div>'
        : '<div class="source-badge computer"><span class="badge-dot">●</span> Local System</div>';

      node.innerHTML = `
        <div class="${avatarClass}" title="${isAi ? 'Generated by GoGlobal Gemini AI' : 'Generated by Local System Engine'}">${avatarLabel}</div>
        <div class="bubble">
          ${sourceBadge}
          <div class="message-text">${escapeHtml(text)}</div>
          ${content}
        </div>
      `;
    }

    $('#messageStream').appendChild(node);
    $('#messageStream').scrollTop = $('#messageStream').scrollHeight;
  }

  function renderCatalog(filter) {
    const source = filter === 'all'
      ? [...(state.catalogue.tours || []), ...(state.catalogue.hotels || []), ...(state.catalogue.flights || [])]
      : state.catalogue[filter] || [];

    $('#catalogList').innerHTML = source.slice(0, 16).map((item) => {
      const type = item.title ? 'Tour' : item.name ? 'Stay' : 'Flight';
      const title = item.title || item.name || `${item.airline} · ${item.from} → ${item.to}`;
      const detail = item.destination || item.city || `${item.duration} · ${item.stops ? `${item.stops} stop` : 'Direct'}`;
      const price = item.price;
      const stars = item.stars ? '★'.repeat(Math.min(item.stars, 5)) : (item.style || 'GoGlobal');
      return `
        <article class="catalog-card">
          <div class="card-top">
            <span class="card-type">${type}</span>
            <span class="card-stars">${stars}</span>
          </div>
          <h3>${escapeHtml(title)}</h3>
          <p>${escapeHtml(detail)}${item.days ? ` · ${item.days} days` : ''}</p>
          <div class="card-price">
            <span>${money(price)} <small>${type === 'Stay' ? '/ night' : 'from'}</small></span>
            <button class="card-cta" data-prompt="${type === 'Stay' ? `Show hotel ${title}` : type === 'Flight' ? `Find flight ${title}` : `Build package ${title}`}">View</button>
          </div>
        </article>
      `;
    }).join('');
  }

  function flightsMarkup(items) {
    if (!items || !items.length) return '';
    return `<div class="card-grid">${items.map((item) => `
      <div class="result-card flight-card">
        <div class="card-badge">✈ ${escapeHtml(item.airline)}</div>
        <div class="flight-route">
          <div class="route-point"><strong>${escapeHtml(item.from)}</strong><span>Origin</span></div>
          <div class="route-arrow">➔<small>${escapeHtml(item.duration)}</small></div>
          <div class="route-point"><strong>${escapeHtml(item.to)}</strong><span>Destination</span></div>
        </div>
        <div class="card-tags">
          <span>${item.stops === 0 ? 'Direct Flight' : `${item.stops} Stop`}</span>
          <span>${escapeHtml(item.class || 'Economy')}</span>
        </div>
        <div class="card-footer">
          <div class="card-price-tag">${money(item.price)}</div>
          <button class="btn-card-action" data-prompt="Book flight on ${escapeHtml(item.airline)} ${escapeHtml(item.from)} to ${escapeHtml(item.to)}">Select Flight</button>
        </div>
      </div>
    `).join('')}</div>`;
  }

  function hotelsMarkup(items) {
    if (!items || !items.length) return '';
    return `<div class="card-grid">${items.map((item) => `
      <div class="result-card hotel-card">
        <div class="card-badge">⌂ ${escapeHtml(item.city)}</div>
        <h4 class="card-title">${escapeHtml(item.name)}</h4>
        <div class="card-rating">${'★'.repeat(Math.min(item.stars || 4, 5))} <small>(${item.stars || 4}-Star Stay)</small></div>
        <div class="card-tags">
          ${(item.amenities || []).slice(0, 3).map(a => `<span>${escapeHtml(a)}</span>`).join('')}
          <span>${escapeHtml(item.mealPlan || 'Breakfast')}</span>
        </div>
        <div class="card-footer">
          <div class="card-price-tag">${money(item.price)} <small>/ night</small></div>
          <button class="btn-card-action" data-prompt="Book hotel stay at ${escapeHtml(item.name)} in ${escapeHtml(item.city)}">Select Hotel</button>
        </div>
      </div>
    `).join('')}</div>`;
  }

  function toursMarkup(items) {
    if (!items || !items.length) return '';
    return `<div class="card-grid">${items.map((item) => `
      <div class="result-card tour-card">
        <div class="card-badge">✦ ${escapeHtml(item.destination)}</div>
        <h4 class="card-title">${escapeHtml(item.title)}</h4>
        <div class="card-meta"><span>${item.days} Days</span> · <span>${escapeHtml(item.style || 'Tour')}</span></div>
        <div class="card-tags">
          ${(item.includes || []).slice(0, 3).map(inc => `<span>✓ ${escapeHtml(inc)}</span>`).join('')}
        </div>
        <div class="card-footer">
          <div class="card-price-tag">${money(item.price)} <small>/ person</small></div>
          <button class="btn-card-action" data-prompt="Build me the ${escapeHtml(item.title)} package">Build Trip</button>
        </div>
      </div>
    `).join('')}</div>`;
  }

  function tripMarkup(trip) {
    const {tour, flight, hotel, meal, total, budget} = trip;
    const meter = budget ? `<div class="trip-line"><span>Budget headroom</span><strong class="text-green">${money(Math.max(budget - total, 0))}</strong></div>` : '';
    return `
      <div class="trip-card">
        <div class="trip-header">
          <span class="trip-badge">Full Itinerary</span>
          <h3>${escapeHtml(tour.title)}</h3>
        </div>
        <div class="trip-line"><span>✈ Flight · ${escapeHtml(flight?.airline || 'Flexible')} (${flight?.from || ''} → ${flight?.to || ''})</span><strong>${money(flight?.price)}</strong></div>
        <div class="trip-line"><span>⌂ Stay · ${escapeHtml(hotel?.name || 'Selected Hotel')}</span><strong>${money(hotel?.price)} / night</strong></div>
        <div class="trip-line"><span>◒ Dining · ${escapeHtml(meal?.plan || 'Daily Meals')}</span><strong>${money(meal?.price)}</strong></div>
        ${meter}
        <div class="trip-total">
          <span>Total Trip Price</span>
          <span class="total-price">${money(total)}</span>
        </div>
        <div class="trip-actions">
          <button data-trip-action="flight">Change Flight</button>
          <button data-trip-action="hotel">Change Hotel</button>
          <button class="primary" data-trip-action="booking">Proceed to Booking</button>
          <button class="whatsapp" data-trip-whatsapp="${escapeHtml(tour.title)}" title="Inquire on WhatsApp">WhatsApp 💬</button>
        </div>
      </div>
    `;
  }

  function bookingCardMarkup() {
    return `
      <div class="inline-booking-card">
        <h3>One Step From Takeoff ✈</h3>
        <p>Complete your booking request below. Our concierge will verify availability instantly.</p>
        <form class="booking-form inline-booking-form">
          <label>Full Name<input name="name" required placeholder="Your full name"></label>
          <label>WhatsApp Number<input name="whatsapp" required placeholder="+92 300 0000000"></label>
          <label>Departure Date<input name="date" type="date" required></label>
          <label>Special Instructions<textarea name="notes" rows="2" placeholder="Room preference, assistance needed..."></textarea></label>
          <button class="primary-action" type="submit">Send Booking Request ➜</button>
        </form>
      </div>
    `;
  }

  function alternativeMarkup(items) {
    return `
      <div class="choice-list">
        ${items.map((item) => `
          <div class="choice-item">
            <div>
              <h3>${escapeHtml(item.title)}</h3>
              <p>${item.days} days · ${money(item.price)} · ${escapeHtml(item.style || 'Value')}</p>
            </div>
            <button data-alternative="${escapeHtml(item.id)}">Choose</button>
          </div>
        `).join('')}
      </div>
    `;
  }

  function followUpChips(type) {
    if (type === 'flights') {
      return `
        <div class="follow-up-chips">
          <button data-prompt="Search hotels in this city">⌂ Find hotels</button>
          <button data-prompt="Show tour packages">✦ View packages</button>
          <button data-prompt="Book a flight">✈ Book flight</button>
        </div>
      `;
    }
    if (type === 'hotels') {
      return `
        <div class="follow-up-chips">
          <button data-prompt="Search flights to this destination">✈ Find flights</button>
          <button data-prompt="Show tour packages">✦ Compare packages</button>
          <button data-prompt="Book hotel room">⌂ Reserve stay</button>
        </div>
      `;
    }
    if (type === 'tours') {
      return `
        <div class="follow-up-chips">
          <button data-prompt="I want to book this package">➜ Book package</button>
          <button data-prompt="Search flights">✈ Check flights</button>
          <button data-prompt="Explore hotels">⌂ Explore hotels</button>
        </div>
      `;
    }
    if (type === 'trip') {
      return `
        <div class="follow-up-chips">
          <button data-trip-action="booking">➜ Proceed to booking</button>
          <button data-trip-action="flight">✈ Swap flight</button>
          <button data-trip-action="hotel">⌂ Swap hotel</button>
        </div>
      `;
    }
    return '';
  }

  async function sendMessage(message) {
    if (!message.trim()) return;
    $('#welcomeBlock').classList.add('hidden');
    appendMessage(message, 'user');
    $('#messageInput').value = '';

    const loading = document.createElement('div');
    loading.className = 'message ai';
    loading.innerHTML = '<div class="avatar ai">✦ AI</div><div class="bubble">Matching live catalogue <span class="loading-dots">···</span></div>';
    $('#messageStream').appendChild(loading);
    $('#messageStream').scrollTop = $('#messageStream').scrollHeight;

    try {
      const data = await request({action: 'chat', message, chat_id: state.sessionId});
      loading.remove();
      const reply = data.reply || {};
      const source = data.source || 'ai';

      let cardContent = '';
      if (reply.type === 'flights') {
        cardContent = flightsMarkup(reply.items) + followUpChips('flights');
      } else if (reply.type === 'hotels') {
        cardContent = hotelsMarkup(reply.items) + followUpChips('hotels');
      } else if (reply.type === 'tours') {
        cardContent = toursMarkup(reply.items) + followUpChips('tours');
      } else if (reply.type === 'trip') {
        state.trip = reply.trip;
        cardContent = tripMarkup(state.trip) + followUpChips('trip');
      } else if (reply.type === 'booking') {
        cardContent = bookingCardMarkup();
      } else if (reply.type === 'alternatives') {
        cardContent = alternativeMarkup(reply.alternatives || []);
      }

      appendMessage(reply.text || 'Here are the options I found for you.', 'ai', cardContent, source);
      saveSession(message);
    } catch (error) {
      loading.remove();
      appendMessage(error.message || 'Something went wrong. Please try again.', 'ai', '', 'computer');
      showToast(error.message || 'An error occurred.');
    }
  }

  function saveSession(firstMessage) {
    const existing = state.sessions.find((session) => session.id === state.sessionId);
    if (existing) return;
    state.sessions.unshift({
      id: state.sessionId,
      title: sessionTitle(firstMessage),
      created: Date.now()
    });
    localStorage.setItem('gg_sessions', JSON.stringify(state.sessions));
    renderSessions();
  }

  function renderSessions() {
    $('#sessionList').innerHTML = state.sessions.slice(0, 10).map((session) => `
      <button class="session-link ${session.id === state.sessionId ? 'active' : ''}" data-session="${session.id}">${escapeHtml(session.title)}</button>
    `).join('');
  }

  function showModal(id) { $(id).classList.remove('hidden'); }
  function closeModals() { document.querySelectorAll('.modal-backdrop').forEach((modal) => modal.classList.add('hidden')); }
  function showToast(message) {
    const toast = $('#toast');
    toast.textContent = message;
    toast.classList.remove('hidden');
    setTimeout(() => toast.classList.add('hidden'), 4500);
  }

  function openChoices(kind) {
    const isFlight = kind === 'flight';
    const items = isFlight ? state.catalogue.flights : state.catalogue.hotels;
    $('#modalEyebrow').textContent = isFlight ? 'Flight Options' : 'Hotel Stay Options';
    $('#modalTitle').textContent = isFlight ? 'Select Flight' : 'Select Hotel';
    $('#modalContent').innerHTML = `
      <div class="choice-list">
        ${(items || []).slice(0, 15).map((item) => `
          <div class="choice-item">
            <div>
              <h3>${escapeHtml(isFlight ? `${item.airline} · ${item.from} → ${item.to}` : item.name)}</h3>
              <p>${escapeHtml(isFlight ? `${item.duration} · ${item.stops ? `${item.stops} stop` : 'Direct'} · ${item.class}` : `${item.city} · ${item.stars}-star · ${item.mealPlan}`)}</p>
            </div>
            <button data-choice-kind="${kind}" data-choice-id="${item.id}">${money(item.price)}</button>
          </div>
        `).join('')}
      </div>
    `;
    showModal('#choiceModal');
  }

  function openBookingModal() {
    if (state.trip) {
      $('#bookingSummary').innerHTML = `
        <div class="booking-summary">
          <strong>${escapeHtml(state.trip.tour.title)}</strong><br>
          ${money(state.trip.total)} · ${state.trip.tour.days} days · ${escapeHtml(state.trip.hotel?.name || 'Selected Hotel')}
        </div>
      `;
    } else {
      $('#bookingSummary').innerHTML = `
        <div class="booking-summary">
          <strong>Custom Travel Request</strong><br>
          Direct inquiry with GoGlobal AI Concierge
        </div>
      `;
    }
    showModal('#bookingModal');
  }

  function setupVoiceRecognition() {
    const voiceBtn = $('#voiceButton');
    const SpeechRecognition = window.SpeechRecognition || window.webkitSpeechRecognition;
    if (!SpeechRecognition) {
      voiceBtn.addEventListener('click', () => showToast('Voice recognition is not supported in this browser. Please type your query.'));
      return;
    }
    const recognition = new SpeechRecognition();
    recognition.continuous = false;
    recognition.interimResults = false;
    recognition.lang = 'en-US';

    let isListening = false;
    voiceBtn.addEventListener('click', () => {
      if (isListening) {
        recognition.stop();
      } else {
        try {
          recognition.start();
          isListening = true;
          voiceBtn.classList.add('listening');
          showToast('Listening... Speak your travel query now.');
        } catch (err) {
          console.error(err);
        }
      }
    });

    recognition.onresult = (event) => {
      const transcript = event.results[0][0].transcript;
      if (transcript) {
        $('#messageInput').value = transcript;
        showToast(`Captured: "${transcript}"`);
      }
    };
    recognition.onend = () => {
      isListening = false;
      voiceBtn.classList.remove('listening');
    };
    recognition.onerror = () => {
      isListening = false;
      voiceBtn.classList.remove('listening');
      showToast('Voice input ended.');
    };
  }

  // Global Click Event Listeners
  document.addEventListener('click', (event) => {
    const prompt = event.target.closest('[data-prompt]');
    if (prompt) {
      closeModals();
      sendMessage(prompt.dataset.prompt);
    }

    const filter = event.target.closest('[data-filter]');
    if (filter) {
      document.querySelectorAll('.filter-tab').forEach((tab) => tab.classList.remove('active'));
      filter.classList.add('active');
      renderCatalog(filter.dataset.filter);
    }

    const action = event.target.closest('[data-trip-action]');
    if (action) {
      const act = action.dataset.tripAction;
      act === 'booking' ? openBookingModal() : openChoices(act);
    }

    const choice = event.target.closest('[data-choice-kind]');
    if (choice) {
      const kind = choice.dataset.choiceKind;
      const list = kind === 'flight' ? state.catalogue.flights : state.catalogue.hotels;
      const selected = list.find((item) => item.id === choice.dataset.choiceId);
      if (state.trip && selected) {
        const previous = state.trip[kind];
        state.trip.total += Number(selected.price || 0) - Number(previous?.price || 0);
        state.trip[kind] = selected;
      }
      closeModals();
      appendMessage(`${kind === 'flight' ? 'Flight' : 'Hotel'} updated to ${selected.airline || selected.name}.`, 'ai', state.trip ? tripMarkup(state.trip) : '', 'ai');
    }

    const alternative = event.target.closest('[data-alternative]');
    if (alternative) {
      const selected = (state.catalogue.tours || []).find((item) => item.id === alternative.dataset.alternative);
      if (selected) {
        closeModals();
        sendMessage(`Please build the ${selected.title} package.`);
      }
    }

    const waBtn = event.target.closest('[data-trip-whatsapp]');
    if (waBtn) {
      const title = waBtn.dataset.tripWhatsapp || 'GoGlobal Package';
      const text = encodeURIComponent(`Hi GoGlobal team! I want to confirm booking for the ${title}. Please share availability.`);
      window.open(`https://wa.me/923000000000?text=${text}`, '_blank');
    }

    if (event.target.closest('[data-close-modal]') || event.target.classList.contains('modal-backdrop')) {
      closeModals();
    }
  });

  // Open capabilities popup
  $('#openCapabilities')?.addEventListener('click', () => {
    showModal('#capabilitiesModal');
  });

  // Forms
  $('#chatForm').addEventListener('submit', (event) => {
    event.preventDefault();
    sendMessage($('#messageInput').value);
  });

  document.addEventListener('submit', async (event) => {
    const form = event.target;
    if (form.id === 'bookingForm' || form.classList.contains('inline-booking-form')) {
      event.preventDefault();
      const booking = Object.fromEntries(new FormData(form));
      booking.trip = state.trip;
      try {
        const result = await request({action: 'booking', booking});
        closeModals();
        form.reset();
        showToast(result.message || 'Booking request sent successfully!');
        appendMessage('Thank you! Your booking request has been submitted. Our WhatsApp team will confirm availability with you shortly.', 'ai', '', 'ai');
      } catch (error) {
        showToast(error.message);
      }
    }
  });

  // Controls
  $('#newChat').addEventListener('click', () => {
    $('#messageStream').innerHTML = '';
    $('#welcomeBlock').classList.remove('hidden');
    state.sessionId = crypto.randomUUID ? crypto.randomUUID() : String(Date.now());
    state.trip = null;
    renderSessions();
    $('#sidebar').classList.remove('open');
  });

  $('#resetConversation').addEventListener('click', () => $('#newChat').click());
  $('#clearSessions').addEventListener('click', () => {
    state.sessions = [];
    localStorage.removeItem('gg_sessions');
    renderSessions();
  });
  $('#mobileMenu').addEventListener('click', () => $('#sidebar').classList.toggle('open'));

  // Init
  setupVoiceRecognition();
  loadCatalogue().catch(() => showToast('Catalogue could not be loaded.'));
  renderSessions();
})();
